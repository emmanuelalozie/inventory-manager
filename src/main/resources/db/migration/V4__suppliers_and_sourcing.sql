-- Suppliers, and how each product is replenished: bought from a supplier or made in-house, with an optional
-- reorder point (restock when quantity <= reorder_point) and reorder quantity (how many to order or make).

CREATE TABLE suppliers (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    email      VARCHAR(255),
    phone      VARCHAR(50),
    notes      VARCHAR(1000),
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    version    BIGINT,
    CONSTRAINT uk_suppliers_name UNIQUE (name)
);

ALTER TABLE products ADD COLUMN source VARCHAR(10) DEFAULT 'BUY' NOT NULL;
ALTER TABLE products ADD COLUMN supplier_id BIGINT;
ALTER TABLE products ADD COLUMN reorder_point INTEGER;
ALTER TABLE products ADD COLUMN reorder_quantity INTEGER;
ALTER TABLE products ADD CONSTRAINT fk_products_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id);
ALTER TABLE products ADD CONSTRAINT ck_products_reorder_point CHECK (reorder_point IS NULL OR reorder_point >= 0);
ALTER TABLE products ADD CONSTRAINT ck_products_reorder_quantity CHECK (reorder_quantity IS NULL OR reorder_quantity > 0);

CREATE INDEX idx_products_supplier ON products (supplier_id);
