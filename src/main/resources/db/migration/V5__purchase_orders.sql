-- Purchase orders to suppliers. Lines can be received in parts; each receipt writes a RECEIPT stock movement
-- with purchase_order_id set (that column already exists on stock_movements, see V2).

CREATE TABLE purchase_orders (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT       NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    notes       VARCHAR(1000),
    ordered_at  TIMESTAMP(6),
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6),
    version     BIGINT,
    CONSTRAINT fk_purchase_orders_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id)
);

CREATE TABLE purchase_order_lines (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT         NOT NULL,
    product_id        BIGINT         NOT NULL,
    quantity_ordered  INTEGER        NOT NULL,
    quantity_received INTEGER        DEFAULT 0 NOT NULL,
    unit_cost         NUMERIC(12, 2),
    CONSTRAINT fk_po_lines_order FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders (id),
    CONSTRAINT fk_po_lines_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_po_lines_ordered CHECK (quantity_ordered > 0),
    CONSTRAINT ck_po_lines_received CHECK (quantity_received >= 0 AND quantity_received <= quantity_ordered),
    CONSTRAINT ck_po_lines_cost CHECK (unit_cost IS NULL OR unit_cost >= 0)
);

CREATE INDEX idx_purchase_orders_supplier ON purchase_orders (supplier_id);
CREATE INDEX idx_purchase_orders_status ON purchase_orders (status);
CREATE INDEX idx_po_lines_order ON purchase_order_lines (purchase_order_id);
CREATE INDEX idx_po_lines_product ON purchase_order_lines (product_id);
