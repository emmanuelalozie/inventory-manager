-- Production runs: making a product in-house. Completing a run adds its quantity to stock with a PRODUCTION
-- movement that points back to the run (stock_movements.production_run_id, no foreign key, like order_id).

CREATE TABLE production_runs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT       NOT NULL,
    quantity     INTEGER      NOT NULL,
    status       VARCHAR(20)  NOT NULL,
    notes        VARCHAR(1000),
    completed_at TIMESTAMP(6),
    created_at   TIMESTAMP(6),
    updated_at   TIMESTAMP(6),
    version      BIGINT,
    CONSTRAINT fk_production_runs_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_production_runs_quantity CHECK (quantity > 0)
);

CREATE INDEX idx_production_runs_product ON production_runs (product_id);
CREATE INDEX idx_production_runs_status ON production_runs (status);

ALTER TABLE stock_movements ADD COLUMN production_run_id BIGINT;
