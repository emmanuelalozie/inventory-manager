-- Product categories, and each product's unit cost (what one unit costs to buy or make). Receiving a purchase
-- order line that has a unit cost updates the product's unit cost to it (last purchase cost).

CREATE TABLE categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    version    BIGINT,
    CONSTRAINT uk_categories_name UNIQUE (name)
);

ALTER TABLE products ADD COLUMN category_id BIGINT;
ALTER TABLE products ADD COLUMN unit_cost NUMERIC(12, 2);
ALTER TABLE products ADD CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id);
ALTER TABLE products ADD CONSTRAINT ck_products_unit_cost CHECK (unit_cost IS NULL OR unit_cost >= 0);

CREATE INDEX idx_products_category ON products (category_id);
