-- 1. Cancelling what is still outstanding on one purchase order line: quantity_cancelled is subtracted from what
--    is still to come, and received + cancelled can never exceed what was ordered.
-- 2. Bills of materials: the components (other products) one unit of a made product uses. Completing a
--    production run takes quantity x run quantity of each component out of stock (CONSUMPTION movements).

ALTER TABLE purchase_order_lines ADD COLUMN quantity_cancelled INTEGER DEFAULT 0 NOT NULL;
ALTER TABLE purchase_order_lines DROP CONSTRAINT ck_po_lines_received;
ALTER TABLE purchase_order_lines ADD CONSTRAINT ck_po_lines_quantities
    CHECK (quantity_received >= 0 AND quantity_cancelled >= 0
           AND quantity_received + quantity_cancelled <= quantity_ordered);

CREATE TABLE product_components (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT  NOT NULL,
    component_id BIGINT  NOT NULL,
    quantity     INTEGER NOT NULL,
    CONSTRAINT fk_components_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT fk_components_component FOREIGN KEY (component_id) REFERENCES products (id),
    CONSTRAINT uk_components UNIQUE (product_id, component_id),
    CONSTRAINT ck_components_quantity CHECK (quantity > 0),
    CONSTRAINT ck_components_not_self CHECK (product_id <> component_id)
);

CREATE INDEX idx_components_component ON product_components (component_id);
